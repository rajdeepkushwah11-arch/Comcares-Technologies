<script>
    (function() {
        'use strict';
        var reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

        /* ---- scroll reveal ---- */
        var revealEls = document.querySelectorAll('.next-animate');
        if ('IntersectionObserver' in window) {
            var io = new IntersectionObserver(function(entries) {
                entries.forEach(function(e) {
                    if (e.isIntersecting) {
                        e.target.classList.add('next-in');
                        io.unobserve(e.target);
                    }
                });
            }, {
                threshold: 0.15
            });
            revealEls.forEach(function(el) {
                io.observe(el);
            });
        } else {
            revealEls.forEach(function(el) {
                el.classList.add('next-in');
            });
        }

        /* ---- hero counters handled by shared assets/counters.js ---- */

        /* ---- button ripple ---- */
        document.querySelectorAll('.next-ripple').forEach(function(btn) {
            btn.addEventListener('click', function(ev) {
                var r = btn.getBoundingClientRect(),
                    d = Math.max(r.width, r.height) * 2,
                    s = document.createElement('span');
                s.className = 'next-ink';
                s.style.width = s.style.height = d + 'px';
                s.style.left = (ev.clientX - r.left - d / 2) + 'px';
                s.style.top = (ev.clientY - r.top - d / 2) + 'px';
                btn.appendChild(s);
                setTimeout(function() {
                    s.remove();
                }, 700);
            });
        });

        /* ---- timeline chapters draw in one by one ---- */
        var chapters = document.querySelectorAll('.next-chapter');
        if ('IntersectionObserver' in window && !reduce) {
            var tio = new IntersectionObserver(function(entries) {
                entries.forEach(function(e) {
                    if (e.isIntersecting) {
                        var i = Array.prototype.indexOf.call(chapters, e.target);
                        e.target.style.transitionDelay = (i * 0.12) + 's';
                        e.target.classList.add('chapter-in');
                        tio.unobserve(e.target);
                    }
                });
            }, {
                threshold: 0.3
            });
            chapters.forEach(function(el) {
                tio.observe(el);
            });
        } else {
            chapters.forEach(function(el) {
                el.classList.add('chapter-in');
            });
        }

        /* ---- team avatar follow-glow ---- */
        if (!reduce && window.matchMedia('(hover: hover)').matches) {
            document.querySelectorAll('.next-person').forEach(function(card) {
                var avatar = card.querySelector('.next-person-avatar');
                card.addEventListener('mousemove', function(e) {
                    var r = card.getBoundingClientRect(),
                        x = (e.clientX - r.left - r.width / 2) / r.width,
                        y = (e.clientY - r.top - r.height / 2) / r.height;
                    card.style.transform = 'translateY(-6px)';
                    if (avatar) avatar.style.transform = 'translate(' + (x * 14) + 'px,' + (y * 14) + 'px) scale(1.06)';
                });
                card.addEventListener('mouseleave', function() {
                    card.style.transform = '';
                    if (avatar) avatar.style.transform = '';
                });
            });
        }
    })();
</script>

